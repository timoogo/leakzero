import { z } from 'zod';
import { CONVERSATION_ID, MAX_NAME_LENGTH, NotesKeys } from './keys';

export { CONVERSATION_ID, MAX_NAME_LENGTH, NOTES_ENABLED } from './keys';
/** Of the stored HTML; chrome.storage.local holds 10 MB in all. */
export const MAX_HTML_LENGTH = 1_000_000;

export const noteIdSchema = z.string().regex(/^[A-Za-z0-9-]{1,64}$/);
export const conversationSchema = z.strictObject({
  id: z.string().regex(CONVERSATION_ID),
  /** Null while Snapchat does not show it (yet). */
  name: z.string().trim().min(1).max(MAX_NAME_LENGTH).nullable(),
});
const timestamp = z.number().int().nonnegative();
export const customNameSchema = z.string().trim().min(1).max(MAX_NAME_LENGTH);

export const noteSchema = z.strictObject({
  /** Generated by LeakZero; never a Snapchat id. */
  id: noteIdSchema,
  /** The Snapchat conversation followed by this note; null for a copy detached from it (import). */
  conversationId: z.string().regex(CONVERSATION_ID).nullable(),
  /** As Snapchat shows it; follows Snapchat, never edited by hand. */
  name: z.string().min(1).max(MAX_NAME_LENGTH),
  /** Title given by hand, shown instead of `name`; never changed by Snapchat. Absent from older notes. */
  customName: customNameSchema.nullable().default(null),
  /** Rich text, limited to the editor schema (src/notes/page/editor.ts). */
  html: z.string().max(MAX_HTML_LENGTH),
  createdAt: timestamp,
  /** Last content change. */
  updatedAt: timestamp,
  /** Last time the conversation was opened on Snapchat. */
  lastSeenAt: timestamp,
  /** In the trash since; kept until deleted for good by hand. */
  trashedAt: timestamp.nullable(),
});

export type Note = z.infer<typeof noteSchema>;

/** The title shown for a note: its custom title, else the name detected on Snapchat. */
export const displayName = (note: Pick<Note, 'name' | 'customName'>) => note.customName ?? note.name;
export type Conversation = z.infer<typeof conversationSchema>;

export interface ActiveConversation {
  /** Snapchat's UUID: the identity of the conversation, never its name. */
  conversationId: string;
  name: string;
  /** Tab it was detected in. */
  tabId: number | null;
  detectedAt: number;
}

/** Name of a conversation whose name was never found on the page. */
export function unnamedConversation(conversationId: string): string {
  return `Conversation ${conversationId.slice(0, 8)}`;
}

/** Every valid note of `items` (a chrome.storage.local snapshot); corrupt entries are skipped. */
export function readNotes(items: Record<string, unknown>): Note[] {
  const notes: Note[] = [];
  for (const [key, value] of Object.entries(items)) {
    if (!key.startsWith(NotesKeys.notePrefix)) continue;
    const parsed = noteSchema.safeParse(value);
    if (parsed.success && key === `${NotesKeys.notePrefix}${parsed.data.id}`) notes.push(parsed.data);
  }
  return notes;
}

export function readOrder(items: Record<string, unknown>): string[] | null {
  const parsed = z.array(z.string()).safeParse(items[NotesKeys.order]);
  return parsed.success ? parsed.data : null;
}

export function activeConversation(items: Record<string, unknown>): ActiveConversation | null {
  const parsed = z.object({
    conversationId: z.string().regex(CONVERSATION_ID),
    name: z.string(),
    // Absent from records written before it was added.
    tabId: z.number().int().nullable().default(null),
    detectedAt: timestamp,
  }).safeParse(items[NotesKeys.active]);
  return parsed.success ? parsed.data : null;
}

/** Activity shown by the default sort: last opened on Snapchat or last edited. */
export function lastActivity(note: Note): number {
  return Math.max(note.lastSeenAt, note.updatedAt);
}
